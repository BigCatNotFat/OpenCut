const ATTRIBUTES = ["title", "placeholder", "aria-label", "aria-description", "alt"];

const PATTERNS = [
  [/^Created\s+(.+)$/, "创建于 $1"],
  [/^Modified\s+(.+)$/, "修改于 $1"],
  [/^Delete\s+(\d+)\s+projects?$/, "删除 $1 个项目"],
  [/^(\d+)\s+projects? selected$/, "已选择 $1 个项目"],
  [/^Scene\s+(\d+)$/, "场景 $1"],
  [/^Track\s+(\d+)$/, "轨道 $1"],
];

function translateCore(value) {
  if (!value) return value;
  const exact = TRANSLATIONS[value];
  if (exact) return exact;
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}

function translatePreservingWhitespace(value) {
  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  if (!match) return value;
  const translated = translateCore(match[2]);
  return `${match[1]}${translated}${match[3]}`;
}

function shouldSkip(element) {
  if (!element) return true;
  return Boolean(
    element.closest(
      "script, style, code, pre, textarea, input, [contenteditable='true'], [data-opencut-no-translate]",
    ),
  );
}

function translateTextNode(node) {
  const parent = node.parentElement;
  if (shouldSkip(parent)) return;
  const nextValue = translatePreservingWhitespace(node.nodeValue || "");
  if (nextValue !== node.nodeValue) node.nodeValue = nextValue;
}

function translateElement(element) {
  if (!(element instanceof Element) || shouldSkip(element)) return;

  for (const attribute of ATTRIBUTES) {
    if (!element.hasAttribute(attribute)) continue;
    const current = element.getAttribute(attribute);
    const translated = translateCore(current || "");
    if (translated !== current) element.setAttribute(attribute, translated);
  }

  for (const child of element.childNodes) {
    if (child.nodeType === Node.TEXT_NODE) translateTextNode(child);
  }
}

function translateTree(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }
  if (!(root instanceof Element) && root !== document) return;

  if (root instanceof Element) translateElement(root);
  root.querySelectorAll?.("*").forEach(translateElement);
}

function activateChineseUi() {
  document.documentElement.lang = "zh-CN";
  document.documentElement.dataset.opencutLocale = "zh-CN";

  const style = document.createElement("style");
  style.dataset.opencutChineseUi = "true";
  style.textContent = `
    html, body, button, input, textarea, select {
      font-family: Inter, "Microsoft YaHei UI", "Microsoft YaHei", "PingFang SC", "Noto Sans CJK SC", sans-serif !important;
    }
  `;
  document.head.appendChild(style);

  translateTree(document);

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (
        mutation.type === "attributes" &&
        mutation.target === document.documentElement &&
        mutation.attributeName === "lang"
      ) {
        if (document.documentElement.lang !== "zh-CN") {
          document.documentElement.lang = "zh-CN";
        }
        continue;
      }
      if (mutation.type === "characterData") {
        translateTextNode(mutation.target);
      } else if (mutation.type === "attributes") {
        translateElement(mutation.target);
      } else {
        mutation.addedNodes.forEach(translateTree);
      }
    }
  });

  observer.observe(document.documentElement, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...ATTRIBUTES, "lang"],
  });
}

if (document.readyState === "loading") {
  window.addEventListener("DOMContentLoaded", activateChineseUi, { once: true });
} else {
  activateChineseUi();
}
